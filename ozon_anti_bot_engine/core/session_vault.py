"""Session vault: cookie persistence (Netscape + JSON) and proactive refresh.

Ozon's fast HTTP path only works while the browser-minted cookies are hot. The
vault owns their lifecycle (spec §3.3):

* read/write both ``cookies.txt`` (Netscape) and JSON,
* track time-to-expiry for the critical cookies (``__Secure-ETC``, ``xcid``),
* run a background watcher that fires a re-bootstrap **5 minutes before** the
  earliest critical expiry, so a long scrape never stalls mid-pagination.
"""

from __future__ import annotations

import asyncio
import json
import logging
import time
from collections.abc import Awaitable, Callable, Iterable, Mapping, Sequence
from dataclasses import asdict, dataclass, field
from pathlib import Path

from .anti_bot import CRITICAL_COOKIES

logger = logging.getLogger(__name__)

RefreshCallback = Callable[[], Awaitable[None]]


# =============================================================================
#  Cookie record
# =============================================================================
@dataclass(slots=True)
class CookieRecord:
    """One cookie, in a shape that round-trips through Playwright and curl."""

    name: str
    value: str
    domain: str = ".ozon.ru"
    path: str = "/"
    expires: float | None = None  # POSIX seconds; None = session cookie
    secure: bool = True
    http_only: bool = False
    same_site: str | None = None

    # --- conversions ---------------------------------------------------
    @classmethod
    def from_playwright(cls, cookie: Mapping[str, object]) -> CookieRecord:
        expires = cookie.get("expires")
        # Playwright encodes "session cookie" as -1.
        expiry = float(expires) if isinstance(expires, (int, float)) and expires > 0 else None
        return cls(
            name=str(cookie.get("name", "")),
            value=str(cookie.get("value", "")),
            domain=str(cookie.get("domain", ".ozon.ru")),
            path=str(cookie.get("path", "/")),
            expires=expiry,
            secure=bool(cookie.get("secure", False)),
            http_only=bool(cookie.get("httpOnly", False)),
            same_site=str(cookie["sameSite"]) if cookie.get("sameSite") else None,
        )

    def to_playwright(self) -> dict[str, object]:
        cookie: dict[str, object] = {
            "name": self.name,
            "value": self.value,
            "domain": self.domain,
            "path": self.path,
            "secure": self.secure,
            "httpOnly": self.http_only,
        }
        if self.expires is not None:
            cookie["expires"] = self.expires
        if self.same_site in ("Strict", "Lax", "None"):
            cookie["sameSite"] = self.same_site
        return cookie

    # --- expiry --------------------------------------------------------
    @property
    def is_session_cookie(self) -> bool:
        return self.expires is None

    def seconds_left(self, now: float | None = None) -> float | None:
        if self.expires is None:
            return None
        return self.expires - (now if now is not None else time.time())

    def is_expired(self, now: float | None = None) -> bool:
        left = self.seconds_left(now)
        return left is not None and left <= 0


# =============================================================================
#  Netscape cookies.txt
# =============================================================================
_NETSCAPE_HEADER = (
    "# Netscape HTTP Cookie File\n"
    "# Generated by Ozon B2B Engine. Do not edit while a scrape is running.\n"
)


def dump_netscape(cookies: Sequence[CookieRecord]) -> str:
    lines = [_NETSCAPE_HEADER]
    for cookie in cookies:
        # curl's convention: an "#HttpOnly_" prefix marks HttpOnly cookies.
        domain = f"#HttpOnly_{cookie.domain}" if cookie.http_only else cookie.domain
        lines.append(
            "\t".join(
                (
                    domain,
                    "TRUE" if cookie.domain.startswith(".") else "FALSE",
                    cookie.path,
                    "TRUE" if cookie.secure else "FALSE",
                    str(int(cookie.expires or 0)),
                    cookie.name,
                    cookie.value,
                )
            )
        )
    return "\n".join(lines) + "\n"


def parse_netscape(text: str) -> list[CookieRecord]:
    cookies: list[CookieRecord] = []
    for raw_line in text.splitlines():
        line = raw_line.strip()
        http_only = False
        if line.startswith("#HttpOnly_"):
            http_only = True
            line = line[len("#HttpOnly_"):]
        elif not line or line.startswith("#"):
            continue

        parts = line.split("\t")
        if len(parts) != 7:
            continue
        domain, _include_sub, path, secure, expires, name, value = parts
        try:
            expiry = float(expires)
        except ValueError:
            expiry = 0.0
        cookies.append(
            CookieRecord(
                name=name,
                value=value,
                domain=domain,
                path=path,
                expires=expiry if expiry > 0 else None,
                secure=secure.upper() == "TRUE",
                http_only=http_only,
            )
        )
    return cookies


# =============================================================================
#  Vault
# =============================================================================
@dataclass
class SessionState:
    """Everything that identifies one warmed-up Ozon session."""

    name: str = "default"
    cookies: list[CookieRecord] = field(default_factory=list)
    user_agent: str | None = None
    profile: str | None = None
    area_id: int | None = None
    proxy: str | None = None       # redacted form only
    created_at: float = field(default_factory=time.time)
    updated_at: float = field(default_factory=time.time)


class SessionVault:
    """Persists and refreshes Ozon session cookies."""

    def __init__(
        self,
        directory: Path | str,
        *,
        refresh_margin: int = 300,
        watch_interval: int = 60,
        cookie_format: str = "json",
    ) -> None:
        self.directory = Path(directory)
        self.directory.mkdir(parents=True, exist_ok=True)
        self.refresh_margin = refresh_margin
        self.watch_interval = watch_interval
        self.cookie_format = cookie_format

        self._states: dict[str, SessionState] = {}
        self._refresher: RefreshCallback | None = None
        self._watch_task: asyncio.Task[None] | None = None
        self._refresh_lock = asyncio.Lock()
        self.refresh_count = 0
        self.last_refresh_at: float | None = None

    # ------------------------------------------------------------------
    #  Paths
    # ------------------------------------------------------------------
    def _json_path(self, name: str) -> Path:
        return self.directory / f"{name}.session.json"

    def _netscape_path(self, name: str) -> Path:
        return self.directory / f"{name}.cookies.txt"

    # ------------------------------------------------------------------
    #  State access
    # ------------------------------------------------------------------
    def state(self, name: str = "default") -> SessionState:
        if name not in self._states:
            self._states[name] = self.load(name) or SessionState(name=name)
        return self._states[name]

    def cookies(self, name: str = "default") -> list[CookieRecord]:
        return self.state(name).cookies

    def cookie_dict(self, name: str = "default") -> dict[str, str]:
        """``{name: value}`` — the shape curl_cffi wants."""
        return {c.name: c.value for c in self.cookies(name) if not c.is_expired()}

    def cookie_header(self, name: str = "default") -> str:
        return "; ".join(f"{k}={v}" for k, v in self.cookie_dict(name).items())

    def update(
        self,
        cookies: Iterable[Mapping[str, object]] | Iterable[CookieRecord],
        *,
        name: str = "default",
        user_agent: str | None = None,
        profile: str | None = None,
        area_id: int | None = None,
        proxy: str | None = None,
        persist: bool = True,
    ) -> SessionState:
        """Merge freshly harvested cookies into the named session."""
        state = self.state(name)
        merged: dict[tuple[str, str, str], CookieRecord] = {
            (c.name, c.domain, c.path): c for c in state.cookies
        }
        for item in cookies:
            record = item if isinstance(item, CookieRecord) else CookieRecord.from_playwright(item)
            if not record.name:
                continue
            merged[(record.name, record.domain, record.path)] = record

        state.cookies = [c for c in merged.values() if not c.is_expired()]
        state.updated_at = time.time()
        if user_agent:
            state.user_agent = user_agent
        if profile:
            state.profile = profile
        if area_id is not None:
            state.area_id = area_id
        if proxy is not None:
            state.proxy = proxy

        if persist:
            self.save(name)
        return state

    def clear(self, name: str = "default") -> None:
        self._states[name] = SessionState(name=name)

    # ------------------------------------------------------------------
    #  Persistence
    # ------------------------------------------------------------------
    def save(self, name: str = "default") -> None:
        state = self.state(name)
        if self.cookie_format in ("json", "both"):
            payload = {
                "name": state.name,
                "user_agent": state.user_agent,
                "profile": state.profile,
                "area_id": state.area_id,
                "proxy": state.proxy,
                "created_at": state.created_at,
                "updated_at": state.updated_at,
                "cookies": [asdict(c) for c in state.cookies],
            }
            self._atomic_write(
                self._json_path(name), json.dumps(payload, ensure_ascii=False, indent=2)
            )
        if self.cookie_format in ("netscape", "both"):
            self._atomic_write(self._netscape_path(name), dump_netscape(state.cookies))

    def load(self, name: str = "default") -> SessionState | None:
        json_path = self._json_path(name)
        if json_path.is_file():
            try:
                payload = json.loads(json_path.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError) as exc:
                logger.warning("could not read session %s: %s", name, exc)
            else:
                cookies = [CookieRecord(**c) for c in payload.get("cookies", [])]
                return SessionState(
                    name=payload.get("name", name),
                    cookies=[c for c in cookies if not c.is_expired()],
                    user_agent=payload.get("user_agent"),
                    profile=payload.get("profile"),
                    area_id=payload.get("area_id"),
                    proxy=payload.get("proxy"),
                    created_at=payload.get("created_at", time.time()),
                    updated_at=payload.get("updated_at", time.time()),
                )

        netscape_path = self._netscape_path(name)
        if netscape_path.is_file():
            try:
                cookies = parse_netscape(netscape_path.read_text(encoding="utf-8"))
            except OSError as exc:
                logger.warning("could not read cookies.txt for %s: %s", name, exc)
                return None
            return SessionState(
                name=name, cookies=[c for c in cookies if not c.is_expired()]
            )
        return None

    def import_netscape(self, path: Path | str, name: str = "default") -> SessionState:
        cookies = parse_netscape(Path(path).read_text(encoding="utf-8"))
        return self.update(cookies, name=name)

    def export_netscape(self, path: Path | str, name: str = "default") -> Path:
        target = Path(path)
        self._atomic_write(target, dump_netscape(self.cookies(name)))
        return target

    @staticmethod
    def _atomic_write(path: Path, content: str) -> None:
        """Write via a temp file + rename so a crash cannot truncate the vault."""
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_text(content, encoding="utf-8")
        tmp.replace(path)
        try:
            path.chmod(0o600)  # cookies are credentials
        except OSError:  # pragma: no cover - non-POSIX filesystems
            pass

    # ------------------------------------------------------------------
    #  Freshness
    # ------------------------------------------------------------------
    def missing_critical(self, name: str = "default") -> list[str]:
        present = {c.name for c in self.cookies(name) if not c.is_expired()}
        return [c for c in CRITICAL_COOKIES if c not in present]

    def seconds_to_expiry(self, name: str = "default") -> float | None:
        """Time until the *earliest* critical cookie expires, or ``None``."""
        lifetimes = [
            left
            for cookie in self.cookies(name)
            if cookie.name in CRITICAL_COOKIES
            and (left := cookie.seconds_left()) is not None
        ]
        return min(lifetimes) if lifetimes else None

    def needs_refresh(self, name: str = "default") -> bool:
        """True when the session is missing critical cookies or is about to expire."""
        # __Secure-ab-group is an A/B bucket and is not always issued; requiring
        # it would trigger endless refreshes on accounts that never receive one.
        required = {"__Secure-ETC", "xcid"}
        present = {c.name for c in self.cookies(name) if not c.is_expired()}
        if required - present:
            return True
        remaining = self.seconds_to_expiry(name)
        return remaining is not None and remaining <= self.refresh_margin

    # ------------------------------------------------------------------
    #  Background watcher
    # ------------------------------------------------------------------
    def register_refresher(self, callback: RefreshCallback) -> None:
        """Register the coroutine that re-bootstraps a session via the browser."""
        self._refresher = callback

    async def refresh_now(self, name: str = "default") -> bool:
        """Run the registered refresher, guarded so only one runs at a time."""
        if self._refresher is None:
            logger.debug("no refresher registered; skipping refresh")
            return False
        async with self._refresh_lock:
            # Another waiter may have refreshed while we queued on the lock.
            if not self.needs_refresh(name):
                return True
            logger.info("refreshing session %r (expiry margin reached)", name)
            try:
                await self._refresher()
            except Exception:
                logger.exception("session refresh failed")
                return False
            self.refresh_count += 1
            self.last_refresh_at = time.time()
            return True

    async def _watch_loop(self, name: str) -> None:
        while True:
            try:
                await asyncio.sleep(self.watch_interval)
                if self.needs_refresh(name):
                    await self.refresh_now(name)
            except asyncio.CancelledError:
                raise
            except Exception:  # pragma: no cover - watchdog must never die
                logger.exception("session watcher iteration failed")

    def start_watch(self, name: str = "default") -> None:
        if self._watch_task is not None and not self._watch_task.done():
            return
        self._watch_task = asyncio.create_task(
            self._watch_loop(name), name="session-vault-watcher"
        )
        logger.info(
            "session watcher started (interval=%ss, margin=%ss)",
            self.watch_interval, self.refresh_margin,
        )

    async def stop_watch(self) -> None:
        if self._watch_task is None:
            return
        self._watch_task.cancel()
        try:
            await self._watch_task
        except asyncio.CancelledError:
            pass
        self._watch_task = None

    # ------------------------------------------------------------------
    def stats(self, name: str = "default") -> dict[str, object]:
        state = self.state(name)
        return {
            "session": name,
            "cookies": len(state.cookies),
            "missing_critical": self.missing_critical(name),
            "seconds_to_expiry": self.seconds_to_expiry(name),
            "needs_refresh": self.needs_refresh(name),
            "refresh_count": self.refresh_count,
            "last_refresh_at": self.last_refresh_at,
            "watcher_running": self._watch_task is not None and not self._watch_task.done(),
            "updated_at": state.updated_at,
        }
